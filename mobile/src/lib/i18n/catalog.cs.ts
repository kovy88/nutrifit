function czDay(n: number): string {
  if (n === 1) return 'den';
  if (n >= 2 && n <= 4) return 'dny';
  return 'dní';
}

function czWorkout(n: number): string {
  if (n === 1) return 'trénink';
  if (n >= 2 && n <= 4) return 'tréninky';
  return 'tréninků';
}

